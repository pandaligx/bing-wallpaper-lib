#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

#[path = "../../../src/elevate.rs"]
mod elevate;

use nsh_platform_windows::{AppOptions, AppSource, Bundle, run_app, set_ui_sets};
use std::process::ExitCode;

struct FrameLog;

impl log::Log for FrameLog {
    fn enabled(&self, meta: &log::Metadata<'_>) -> bool {
        meta.target() == nsh_engine::perf::LOG_TARGET && meta.level() == log::Level::Info
    }
    fn log(&self, record: &log::Record<'_>) {
        if self.enabled(record.metadata()) {
            use std::io::Write;
            let _ = writeln!(std::io::stderr().lock(), "{}", record.args());
        }
    }
    fn flush(&self) {}
}

fn main() -> ExitCode {
    if std::env::args().nth(1).as_deref() == Some("--install-wallpaper-update") {
        return if std::env::args()
            .nth(2)
            .is_some_and(|v| wallpaper_native::install_update(&v).is_ok())
        {
            ExitCode::SUCCESS
        } else {
            ExitCode::FAILURE
        };
    }
    if let Some(arg) = std::env::args()
        .nth(1)
        .filter(|s| matches!(s.as_str(), "--daily-wallpaper" | "--scheduled-wallpaper"))
    {
        return if wallpaper_native::run_scheduled(&arg).is_ok() {
            ExitCode::SUCCESS
        } else {
            ExitCode::FAILURE
        };
    }
    if std::env::var_os("BING_WALLPAPER_CONFIRM_WINDOW").is_none() && !elevate::ensure_elevated() {
        return ExitCode::SUCCESS;
    }
    let fps = std::env::args().any(|arg| arg == "--fps");
    if fps && log::set_logger(&FrameLog).is_ok() {
        log::set_max_level(log::LevelFilter::Info);
    }
    wallpaper_native::mark_portable();
    set_ui_sets(vec![nsh_base::registry(), wallpaper_native::registry()]);
    // SAFETY: Cargo embeds our own bundle built by the explicitly version-matched NSH CLI.
    let mut bundle =
        unsafe { Bundle::bytecode(include_bytes!("../../.nsh/out/bundle.nshc").to_vec()) };
    bundle.policy.declared = Some(
        nsh_engine::parse_capabilities(include_str!("../../.nsh/out/capabilities.json"))
            .expect("capabilities generated by the pinned NSH compiler"),
    );
    run_app(
        AppSource::Bundle(bundle.with_app_id(Some("cn.lgxng.bingwallpaperlib"))),
        AppOptions {
            app_id: "cn.lgxng.bingwallpaperlib".into(),
            title: format!("必应每日壁纸库 v{}", env!("CARGO_PKG_VERSION")),
            size: (1160, 780),
            single_instance: true,
            fps,
            limits: nsh_platform_windows::Limits::standalone(),
            ..Default::default()
        },
    )
}
